class _UnionFind:  # Track merged electrical points with a lightweight disjoint-set structure.
    def __init__(self) -> None:  # Initialize the disjoint set.
        self._parent: Dict[str, str] = {}  # Map each point key to its current representative.

    def add(self, key: str) -> None:  # Register a point key when it is not already present.
        if key not in self._parent:  # Check whether the key is new.
            self._parent[key] = key  # Start the point as its own representative.

    def find(self, key: str) -> str:  # Resolve the representative of one point key.
        root = key  # Walk upward from the requested key.
        while self._parent.get(root, root) != root:  # Follow parent links until the root is reached.
            root = self._parent[root]  # Move to the parent representative.
        self._parent[key] = root  # Compress the path for the requested key.
        return root  # Return the resolved representative.

    def union(self, first: str, second: str) -> None:  # Merge the sets containing two point keys.
        first_root = self.find(first)  # Resolve the representative of the first key.
        second_root = self.find(second)  # Resolve the representative of the second key.
        if first_root != second_root:  # Only merge when the sets are distinct.
            self._parent[second_root] = first_root  # Attach the second root under the first.


class _LibraryCache:  # Lazily parse KiCad symbol library files found under the configured kicad_path.
    def __init__(self, kicad_path: str) -> None:  # Initialize the cache with the configured root.
        self._search_roots = [kicad_path]  # Search the configured path itself first.
        symbols_directory = os.path.join(kicad_path, "symbols")  # Probe the conventional symbols subdirectory.
        if os.path.isdir(symbols_directory):  # Include the subdirectory when the install layout provides it.
            self._search_roots.append(symbols_directory)  # Add the subdirectory as a secondary search root.
        self._parsed: Dict[str, Optional[SExp]] = {}  # Cache parsed library roots by library nickname.

    def find(self, lib_id: str) -> Optional[SExp]:  # Resolve one library identifier to its symbol node.
        nickname, name = _split_lib_id(lib_id)  # Split the identifier into nickname and symbol name.
        if nickname:  # Fast path: load only the library named by the nickname.
            library_root = self._load_library(nickname)  # Parse the nickname library file.
            symbol_node = _find_symbol_in_root(library_root, name)  # Search the library for the symbol.
            if symbol_node is not None:  # Stop when the named library contains the symbol.
                return _resolve_extends(symbol_node, name, library_root)  # Flatten the inheritance chain before returning.
        if nickname != "":  # Stop when a named library was requested and did not contain the symbol.
            return None  # Return None so the caller can fall back to embedded definitions.
        for search_root in self._search_roots:  # Slow path: scan every library file for colon-less identifiers.
            try:  # Attempt to list the search directory.
                entries = sorted(os.listdir(search_root))  # List entries in deterministic order.
            except OSError:  # Skip directories that cannot be listed.
                continue  # Move to the next search root.
            for entry in entries:  # Walk every directory entry.
                if not entry.endswith(_KICAD_SYMBOL_EXTENSION):  # Skip non-library entries.
                    continue  # Move to the next entry.
                candidate_path = os.path.join(search_root, entry)  # Build the concrete library path for the text prefilter.
                try:  # Read metadata used to invalidate the prefilter cache.
                    file_stat = os.stat(candidate_path)  # Stat the candidate file.
                    if not _library_file_contains_symbol(candidate_path, file_stat.st_mtime_ns, file_stat.st_size, name):  # Avoid parsing libraries that cannot define the requested symbol.
                        continue  # Move to the next library file.
                except (OSError, UnicodeDecodeError):  # Skip unreadable candidate files.
                    continue  # Move to the next entry.
                library_root = self._load_library(entry[: -len(_KICAD_SYMBOL_EXTENSION)])  # Parse the library file.
                symbol_node = _find_symbol_in_root(library_root, name)  # Search for the symbol name.
                if symbol_node is not None:  # Stop at the first library that defines the symbol.
                    return _resolve_extends(symbol_node, name, library_root)  # Flatten the inheritance chain before returning.
        return None  # Return None when no library defines the requested symbol.

    def _load_library(self, nickname: str) -> Optional[SExp]:  # Parse and cache one library file root.
        if nickname in self._parsed:  # Reuse a previously parsed library.
            return self._parsed[nickname]  # Return the cached root node.
        library_root: Optional[SExp] = None  # Default to a missing library.
        for search_root in self._search_roots:  # Walk every search root in order.
            candidate_path = os.path.join(search_root, nickname + _KICAD_SYMBOL_EXTENSION)  # Build the library path.
            if not os.path.isfile(candidate_path):  # Skip roots that do not contain the library file.
                continue  # Move to the next search root.
            try:  # Attempt to read and parse the library file.
                file_stat = os.stat(candidate_path)  # Read metadata used to invalidate the shared parse cache.
                library_root = _load_library_file(candidate_path, file_stat.st_mtime_ns, file_stat.st_size)  # Reuse the parsed read-only tree when unchanged.
                break  # Stop after the first readable library file.
            except (OSError, UnicodeDecodeError, ParseError):  # Treat unreadable libraries as missing.
                library_root = None  # Keep the missing-library default.
        self._parsed[nickname] = library_root  # Cache the parsed root (or None).
        return library_root  # Return the cached library root.


def _resolve_extends(symbol_node: SExp, resolved_name: str, library_root: Optional[SExp]) -> SExp:  # Flatten one extends-based symbol definition into a self-contained node.
    chain: List[SExp] = []  # Collect the inheritance chain from the requested symbol up to the topmost ancestor.
    current = symbol_node  # Start the chain walk at the requested symbol.
    visited: Set[int] = set()  # Guard against cyclic extends directives.
    while id(current) not in visited:  # Walk while the inheritance chain stays acyclic.
        visited.add(id(current))  # Mark the current symbol as visited.
        chain.append(current)  # Append the current symbol to the chain.
        extends_node = current.find_child("extends")  # Locate the extends directive.
        if extends_node is None:  # Stop at symbols that declare no parent.
            break  # End the chain walk.
        extends_values = [child.value for child in extends_node.children if child.is_atom]  # Collect the parent name atoms.
        if not extends_values:  # Stop at malformed extends directives.
            break  # End the chain walk.
        parent_name = str(extends_values[0])  # Read the parent symbol name.
        parent_node = _find_symbol_in_root(library_root, parent_name)  # Look up the parent inside the same library.
        if parent_node is None:  # Stop when the parent cannot be resolved.
            break  # End the chain walk.
        current = parent_node  # Move up the inheritance chain.
    if len(chain) == 1:  # Fast path for symbols that declare no parent.
        return symbol_node  # Return the unchanged symbol node.
    merged: Dict[Tuple[str, Optional[str]], SExp] = {}  # Collect merged sections keyed by tag and first atom.
    for chain_node in reversed(chain):  # Walk from the topmost ancestor down to the requested symbol.
        ancestor_name = _first_atom_value(chain_node)  # Read the ancestor symbol name for sub-symbol renaming.
        for child in chain_node.children:  # Walk every child section of the chain node.
            if child.name == "extends":  # Drop the resolved inheritance directive.
                continue  # Skip the directive from the merged result.
            if child.is_atom:  # Skip the leading name atom of each source symbol.
                continue  # Move to the next section.
            key = (str(child.name), _first_atom_value(child))  # Build the merge key from the tag and first atom.
            merged[key] = _rename_inherited_sections(child, ancestor_name, resolved_name)  # Overlay the section so descendants win.
    merged_children: List[SExp] = [SExp(value=resolved_name)]  # Start the merged children with the resolved name atom.
    for child in merged.values():  # Walk the merged sections in insertion order.
        merged_children.append(child)  # Append each merged section.
    return SExp(name="symbol", children=merged_children)  # Return the flattened self-contained symbol node.


def _rename_inherited_sections(child: SExp, source_name: Optional[str], target_name: str) -> SExp:  # Rename inherited sub-symbols onto the requesting symbol name.
    if child.name != "symbol" or source_name is None:  # Only sub-symbols carry names that need renaming.
        return child  # Return the section unchanged.
    prefix = str(source_name) + "_"  # Build the source sub-symbol name prefix.
    renamed_children: List[SExp] = []  # Collect the renamed sub-symbol children.
    replaced = False  # Track whether the leading name atom was renamed.
    for grandchild in child.children:  # Walk the sub-symbol children.
        if not replaced and grandchild.is_atom:  # Rename the leading name atom only.
            value = str(grandchild.value)  # Read the current name value.
            if value.startswith(prefix):  # Only rename names that belong to the inherited ancestor.
                renamed_children.append(SExp(value=target_name + value[len(prefix) - 1:]))  # Replace the ancestor prefix with the target name.
            else:  # Preserve unrelated name atoms.
                renamed_children.append(grandchild)  # Keep the name unchanged.
            replaced = True  # Mark the leading atom as handled.
        else:  # Keep all remaining children unchanged.
            renamed_children.append(grandchild)  # Preserve the child node.
    return SExp(name=child.name, children=renamed_children)  # Return the renamed sub-symbol node.


@lru_cache(maxsize=64)
def _load_library_file(candidate_path: str, _mtime_ns: int, _size: int) -> SExp:  # Parse one unchanged library file once per process.
    with open(candidate_path, "r", encoding="utf-8") as file_handle:  # Open the configured library path.
        return parse_string(file_handle.read())  # Parse and cache the read-only S-expression tree.


@lru_cache(maxsize=4096)
def _library_file_contains_symbol(candidate_path: str, _mtime_ns: int, _size: int, symbol_name: str) -> bool:  # Cheaply prefilter a library before full S-expression parsing.
    with open(candidate_path, "r", encoding="utf-8") as file_handle:  # Read the configured library text.
        library_text = file_handle.read()  # Load the text for an exact symbol declaration search.
    pattern = rf'\(\s*symbol\s+"{re.escape(symbol_name)}"(?=\s|\))'  # Match an exact quoted symbol name with flexible formatting.
    return re.search(pattern, library_text) is not None  # Report whether full parsing could find the requested symbol.


def kicad_sch_to_ltspice_netlist(  # Convert one KiCad schematic into one LTspice netlist file.
    kicad_sch_filepath: str,  # Accept the KiCad schematic input path.
    ltspice_netlist_filepath_out: str,  # Accept the LTspice netlist output path.
    convert_settings: Mapping,  # Accept the conversion configuration mapping.
) -> ConversionResult:  # Return the shared conversion result tuple.
    """Convert one KiCad ``.kicad_sch`` schematic into one LTspice ``.net`` netlist.

    Symbol definitions are resolved from the schematic's embedded ``lib_symbols``
    definitions first (the instances were authored against that geometry) and
    from the KiCad symbol libraries under ``convert_settings["kicad_path"]``
    when the schematic embeds no definition. Power symbols become LTspice voltage
    sources named after their reference designator (without any leading ``#``)
    with the symbol value as the DC payload; ``GND``/``0`` power symbols become
    node ``0``. Inductors receive LTspice's standard ``Rser=1m`` default and
    three-pin BJT/MOSFET symbols receive the substrate node ``0``.

    Returns ``(True, "OK", 0)`` on success or ``(False, "<error code>", <line>)``
    on failure.
    """
    settings_result = _normalize_convert_settings(convert_settings)  # Validate the conversion settings first.
    if not settings_result[0]:  # Stop when the settings are unusable.
        return False, "INVALID_CONVERT_SETTINGS", 0  # Return the required settings error code.
    kicad_path = settings_result[1]  # Read the validated KiCad library path.
    output_result = _coerce_output_path(ltspice_netlist_filepath_out)  # Coerce the output path safely.
    if not output_result[0]:  # Stop when the output path is not path-like.
        return False, "INVALID_OUTPUT_PATH", 0  # Return the required output path error code.
    output_path = output_result[1]  # Read the coerced output path string.
    input_result = _coerce_input_path(kicad_sch_filepath)  # Coerce and check the input path.
    if not input_result[0]:  # Stop when the input path is unusable.
        return False, "INVALID_KICAD_SCH_FILE", 0  # Return the required schematic file error code.
    input_path = input_result[1]  # Read the coerced input path string.
    validation_result = is_valid_kicad_sch_file(input_path)  # Validate the schematic before conversion.
    if not validation_result[0]:  # Stop when the schematic fails validation.
        return False, "INVALID_KICAD_SCH_FILE", _line_from_message(validation_result[1])  # Return the failing line.
    read_result = _read_text_file_lines(input_path)  # Read the schematic text with encoding detection.
    if not read_result[0]:  # Stop when the schematic cannot be read.
        return False, "KICAD_SCH_READ_ERROR", 0  # Return the required read error code.
    parse_result = _parse_sch_text("\n".join(read_result[1]))  # Parse the schematic into an S-expression tree.
    if not parse_result[0]:  # Stop when the schematic text cannot be parsed.
        return False, "KICAD_SCH_PARSE_ERROR", parse_result[2]  # Return the failing source line.
    build_result = _build_netlist_lines(parse_result[1], kicad_path)  # Build the LTspice netlist line list.
    if not build_result[0]:  # Stop when the conversion logic reports a failure.
        return False, build_result[2], build_result[3]  # Return the conversion error code and line.
    netlist_text = "\n".join(build_result[1]) + "\n"  # Join the generated lines into one netlist text.
    write_result = _write_text_file(output_path, netlist_text)  # Write the generated netlist file.
    if not write_result[0]:  # Stop when the output cannot be written.
        return False, "WRITE_ERROR", 0  # Return the required write error code.
    generated_result = is_valid_ltspice_netlist_file(output_path)  # Validate the freshly written netlist.
    if not generated_result[0]:  # Stop when the generated netlist fails validation.
        return False, "INVALID_GENERATED_NETLIST", _line_from_message(generated_result[1])  # Return the output line.
    return True, "OK", 0  # Return success when the conversion completed.


def _build_netlist_lines(root: SExp, kicad_path: str) -> Tuple[bool, List[str], str, int]:  # Build LTspice netlist lines from a parsed schematic.
    embedded_index = _build_embedded_symbol_index(root)  # Index the schematic's cached lib_symbols definitions.
    library_cache = _LibraryCache(kicad_path)  # Prepare the lazy kicad_path library cache.
    components: List[Dict[str, object]] = []  # Collect parsed symbol instances in file order.
    for index, instance_node in enumerate(root.find_children("symbol")):  # Walk every schematic symbol instance.
        parse_result = _parse_instance(instance_node, index)  # Parse the instance header and properties.
        if not parse_result[0]:  # Stop when an instance record is malformed.
            return False, [], parse_result[2], parse_result[3]  # Return the parse error code and line.
        record = parse_result[1]  # Read the parsed instance record.
        symbol_node = embedded_index.get(record["lib_id"])  # Prefer the schematic's embedded lib_symbols definition the instance was authored against.
        symbol_source = "embedded"  # Track which source resolved the symbol definition.
        if symbol_node is None:  # Fall back to the kicad_path libraries when the schematic embeds no definition.
            symbol_node = library_cache.find(record["lib_id"])  # Resolve the symbol in the kicad_path libraries.
            symbol_source = "library"  # Record the library fallback source.
        if symbol_node is None:  # Stop when the symbol cannot be resolved anywhere.
            message = f"UNKNOWN_KICAD_SYMBOL: Unable to locate KiCad symbol '{record['lib_id']}' in kicad_path or the schematic's lib_symbols section"  # Explain the failed lookup.
            return False, [], message, record["line"]  # Return the unknown symbol error with the instance line.
        record["power"] = symbol_node.find_child("power") is not None  # Detect power symbols from the library definition.
        record["symbol_props"] = _collect_properties(symbol_node)  # Collect the library symbol properties.
        exclude_result = _symbol_excluded_from_sim(symbol_node)  # Check the library-level simulation exclusion.
        if exclude_result:  # Respect the library-level exclusion flag.
            record["exclude"] = True  # Mark the instance as excluded from simulation.
        pins_result = _extract_symbol_pins(symbol_node, record["unit"], record["body_style"], _split_lib_id(str(record["lib_id"]))[1])  # Extract pin geometry.
        if not pins_result[0] and symbol_source == "embedded":  # Retry the kicad_path library when the embedded unit is missing.
            library_node = library_cache.find(record["lib_id"])  # Resolve the library definition.
            if library_node is not None:  # Prefer the library definition when it can supply the requested unit.
                symbol_node = library_node  # Switch to the library symbol node.
                symbol_source = "library"  # Record the library fallback source.
                record["power"] = symbol_node.find_child("power") is not None  # Re-detect power symbols from the library definition.
                record["symbol_props"] = _collect_properties(symbol_node)  # Re-collect the library symbol properties.
                pins_result = _extract_symbol_pins(symbol_node, record["unit"], record["body_style"], _split_lib_id(str(record["lib_id"]))[1])  # Re-extract pin geometry.
        if not pins_result[0]:  # Stop when the symbol carries no usable pin graphics.
            if not _symbol_has_any_pins(symbol_node) and not _symbol_has_any_pins(embedded_index.get(record["lib_id"])):  # Skip purely graphical marker symbols.
                continue  # Move to the next instance.
            message = f"UNKNOWN_KICAD_SYMBOL: symbol '{record['lib_id']}' has no pin definitions for unit {record['unit']}"  # Explain the missing graphics.
            return False, [], message, record["line"]  # Return the unknown symbol error with the instance line.
        if record["power"] and str(record["value"]).upper() == _PWR_FLAG_VALUE:  # Skip PWR_FLAG power markers that carry no electrical function.
            continue  # Move to the next instance.
        record["symbol_pins"] = pins_result[1]  # Store the resolved pin geometry mapping.
        components.append(record)  # Append the finished instance record.
    netlist_result = _wire_and_emit(components, root, kicad_path)  # Trace connectivity and emit the device lines.
    if not netlist_result[0]:  # Stop when wiring or emission reports a failure.
        return netlist_result  # Return the wiring or emission error unchanged.
    return True, netlist_result[1], "", 0  # Return the generated netlist lines on success.


def _wire_and_emit(components: List[Dict[str, object]], root: SExp, kicad_path: str) -> Tuple[bool, List[str], str, int]:  # Trace nets and emit LTspice device lines.
    union_find = _UnionFind()  # Create the point-merging structure for the schematic.
    segments = _collect_wire_segments(root, union_find)  # Collect wire polylines as point-merged segments.
    for junction_x, junction_y in _collect_junction_positions(root):  # Walk every junction record.
        junction_key = _point_key(junction_x, junction_y)  # Register the junction position as a point.
        union_find.add(junction_key)  # Ensure the junction point exists.
        for segment in segments:  # Search for a segment passing through the junction.
            if _point_on_segment(junction_x, junction_y, segment):  # Detect the pass-through segment.
                union_find.union(junction_key, segment[4])  # Join the junction to the segment net.
                break  # Stop after the first passing segment.
    for first_segment in segments:  # Walk every segment as a candidate endpoint owner.
        for second_segment in segments:  # Walk every other segment as a candidate carrier.
            if first_segment is second_segment:  # Skip self comparisons.
                continue  # Move to the next pair.
            if _point_on_segment(first_segment[0], first_segment[1], second_segment):  # Detect a start point resting on another wire.
                union_find.union(first_segment[4], second_segment[4])  # Merge the start point into the carrier net.
            if _point_on_segment(first_segment[2], first_segment[3], second_segment):  # Detect an end point resting on another wire.
                union_find.union(first_segment[5], second_segment[4])  # Merge the end point into the carrier net.
    net_names: Dict[str, str] = {}  # Map net representatives to their assigned names.
    for label_x, label_y, label_text in _collect_label_entries(root):  # Walk every schematic label.
        label_key = _attach_point(union_find, segments, label_x, label_y)  # Attach the label position to its net.
        label_root = union_find.find(label_key)  # Resolve the label net representative.
        if label_text != "" and label_root not in net_names:  # Assign the first label name to each net.
            net_names[label_root] = label_text  # Record the label text as the net name.
    no_connect_keys = {_point_key(x, y) for x, y in _collect_no_connect_positions(root)}  # Index no-connect marker positions.
    for record in components:  # Walk every parsed component.
        if record["exclude"]:  # Excluded components contribute no simulated net memberships.
            continue  # Skip connectors and markers that never appear in the netlist.
        record["pin_nets"] = {}  # Prepare the pin-to-net mapping for this component.
        record["pin_wired"] = {}  # Track which pins physically touch a drawn wire segment.
        for pin_number in record["pin_numbers"]:  # Walk the instance pin numbers.
            pin_data = record["symbol_pins"].get(pin_number)  # Look up the library pin geometry.
            if pin_data is None:  # Skip instance pins that carry no library geometry.
                continue  # Ignore inert pin stubs that are never placed on the schematic.
            pin_x, pin_y, _pin_name = pin_data  # Read the local pin coordinates.
            absolute_x, absolute_y = _transform_point(pin_x, pin_y, float(record["x"]), float(record["y"]), float(record["angle"]), str(record["mirror"]))  # Compute the schematic-space pin position.
            record["pin_wired"][pin_number] = any(_point_on_segment(absolute_x, absolute_y, segment) for segment in segments)  # Remember whether physical copper reaches this pin.
            pin_key = _attach_point(union_find, segments, absolute_x, absolute_y)  # Attach the pin to its electrical net.
            pin_root = union_find.find(pin_key)  # Resolve the pin net representative.
            if pin_key in no_connect_keys:  # Detect pins marked with a no-connect flag.
                no_connect_name = f"NC_{record['reference']}_{record['index']}_{pin_number}"  # Build an exempt no-connect net name unique per instance.
                if pin_root not in net_names:  # Assign the no-connect name when the net is unnamed.
                    net_names[pin_root] = no_connect_name  # Record the no-connect name.
            record["pin_nets"][pin_number] = pin_root  # Store the pin net representative.
            if record["power"]:  # Power symbols name their net after their value.
                power_value = record["value"]  # Read the power symbol value.
                if power_value != "" and pin_root not in net_names:  # Assign the first power value as the net name.
                    net_names[pin_root] = power_value  # Record the power net name.
    normalized_net_names: Dict[str, str] = {}  # Re-key names after later attachments may have changed union-find representatives.
    for net_root, net_name in net_names.items():  # Walk every label and power-derived name.
        normalized_net_names.setdefault(union_find.find(net_root), net_name)  # Preserve the first name assigned to each final representative.
    net_names = normalized_net_names  # Use only final union-find representatives from this point onward.
    explicitly_named_roots = set(net_names)  # Remember labels and power names so singleton labeled pins retain their authored identity.
    for record in components:  # Normalize every stored pin root after all pin and label attachments.
        for pin_number, pin_root in list(record["pin_nets"].items()):  # Walk a stable copy of the pin mapping.
            final_root = union_find.find(pin_root)  # Resolve the final representative.
            record["pin_nets"][pin_number] = final_root  # Replace the stale representative.
    components = _merge_multi_unit_components(components)  # Combine distinct units sharing one physical reference before counting and emission.
    for record in components:  # Supply explicit no-connect nodes for model ports whose symbol unit was not placed.
        if record["exclude"] or record["power"]:  # Only ordinary simulated components have model port mappings.
            continue  # Move to the next record.
        sim_pins_text = _record_property(record, "Sim.Pins")  # Read the authoritative package-to-model port mapping.
        for token in sim_pins_text.split():  # Walk every declared model port.
            if "=" not in token:  # Skip malformed mapping fragments.
                continue  # Move to the next token.
            pin_number = token.split("=", 1)[0].strip()  # Extract the package pin number.
            if pin_number == "" or pin_number in record["pin_nets"]:  # Keep physically resolved ports unchanged.
                continue  # Move to the next mapped port.
            missing_root = f"__NC_PORT_{record['index']}_{pin_number}"  # Build a synthetic isolated net representative.
            record["pin_nets"][pin_number] = missing_root  # Attach the unplaced model port to its own NC net.
            net_names[missing_root] = f"NC_{record['reference']}_{record['index']}_{pin_number}"  # Give the isolated port a validator-exempt node name.
    member_order: Dict[str, Tuple[int, int]] = {}  # Track the earliest component/pin member per net for naming.
    for record in components:  # Walk every component to seed the naming order.
        for pin_number, pin_root in record["pin_nets"].items():  # Walk every pin-to-net association.
            member_key = (record["index"], _pin_sort_key(pin_number))  # Build a deterministic member ordering key.
            if pin_root not in member_order or member_key < member_order[pin_root]:  # Keep the earliest member key.
                member_order[pin_root] = member_key  # Record the earliest member key.
    unnamed_roots = sorted(root_key for root_key in member_order if root_key not in net_names)  # Order unnamed nets deterministically.
    for counter, root_key in enumerate(unnamed_roots, start=1):  # Name each unnamed net in order.
        net_names[root_key] = f"N{counter:03d}"  # Assign the sequential LTspice-style net name.
    named_member_counts: Dict[str, int] = {}  # Count memberships by emitted node name so same-named KiCad labels join separate wire islands.
    for record in components:  # Walk every simulated component.
        for pin_root in record["pin_nets"].values():  # Count every resolved pin port.
            node_name = _node_name_for_net(pin_root, net_names)  # Resolve the final emitted node token.
            named_member_counts[node_name] = named_member_counts.get(node_name, 0) + 1  # Count ports across all identically labeled islands.
    dangling_wire_counter = 0  # Number physically wired nodes that have no second simulated device port.
    for record in components:  # Walk every component again to mark lone floating pins.
        for pin_number, pin_root in record["pin_nets"].items():  # Walk every pin net.
            net_name = net_names.get(pin_root, "")  # Read the resolved net name.
            if net_name.upper() in _GROUND_VALUES:  # Skip ground nets.
                continue  # Move to the next pin.
            if net_name.upper().startswith(_NO_CONNECT_PREFIXES):  # Skip explicitly marked no-connect pins.
                continue  # Move to the next pin.
            if pin_root in explicitly_named_roots:  # A label directly on a pin or dangling wire is a valid KiCad electrical connection.
                continue  # Preserve its authored net name even when only one simulated device port uses it.
            if record["power"]:  # Power pins may sit on nets referenced only by behavioral expressions.
                continue  # Move to the next pin.
            if str(record["reference"])[:1].upper() == "B":  # Behavioral source pins may sit on probe nets referenced only by expressions.
                continue  # Move to the next pin.
            if named_member_counts.get(_node_name_for_net(pin_root, net_names), 0) < 2:  # Detect emitted nets carried by a single device pin.
                if record["pin_wired"].get(pin_number, False):  # Preserve the distinction between real dangling copper and an untouched pin.
                    dangling_wire_counter += 1  # Advance the physical dangling-wire name counter.
                    net_names[pin_root] = f"{_DANGLING_WIRE_PREFIX}{dangling_wire_counter:03d}"  # Assign a non-NC node name that records physical wiring.
                else:  # Truly floating symbol pins remain explicit no-connects.
                    net_names[pin_root] = f"NC_{record['reference']}_{record['index']}_{pin_number}"  # Name the floating pin with a per-instance no-connect prefix.
    model_source_lines = _prepare_model_source_lines(components, kicad_path)  # Resolve model libraries and self-contained fallback models.
    emit_result = _emit_device_lines(components, net_names)  # Emit the LTspice device lines.
    if not emit_result[0]:  # Stop when device emission reports a failure.
        return emit_result  # Return the emission error unchanged.
    singleton_label_lines = [  # Preserve exact metadata for the stricter project connectivity validator.
        _SINGLETON_LABEL_MARKER + _node_name_for_net(root_key, net_names)  # Record the emitted node spelling.
        for root_key in sorted(explicitly_named_roots)  # Keep metadata deterministic.
        if named_member_counts.get(_node_name_for_net(root_key, net_names), 0) < 2  # Mark only true singleton labels.
        and _node_name_for_net(root_key, net_names).upper() not in _GROUND_VALUES  # Ground needs no exemption metadata.
    ]  # Finish singleton-label metadata generation.
    lines = [_GENERATED_NETLIST_MARKER, *singleton_label_lines, *model_source_lines, *emit_result[1]]  # Emit metadata and model sources before device statements.
    schematic_directives = _collect_simulation_directives(root)  # Preserve supported simulation statements stored as schematic text.
    lines.extend(schematic_directives)  # Emit schematic directives after the device statements.
    if not any(_directive_name(line) in _ANALYSIS_DIRECTIVES for line in schematic_directives):  # Supply an analysis only when the schematic has none.
        lines.append(_DEFAULT_ANALYSIS_DIRECTIVE)  # Append the minimal fallback analysis directive.
    lines.append(".backanno")  # Append the required back-annotation directive.
    lines.append(".end")  # Append the required netlist terminator.
    return True, lines, "", 0  # Return the completed netlist lines.


def _merge_multi_unit_components(components: List[Dict[str, object]]) -> List[Dict[str, object]]:  # Merge separately placed units that represent one physical component.
    mergeable_keys: Set[Tuple[str, str]] = set()  # Track reference/library pairs that contain more than one distinct unit.
    units_by_key: Dict[Tuple[str, str], Set[int]] = {}  # Collect unit ordinals for each physical-reference candidate.
    for record in components:  # Inspect every parsed component before merging.
        if record["exclude"] or record["power"]:  # Excluded and power symbols are never multi-unit device calls.
            continue  # Keep these records independent.
        key = (str(record["reference"]).upper(), str(record["lib_id"]))  # Identify one physical part without merging unrelated duplicate references.
        units_by_key.setdefault(key, set()).add(int(record["unit"]))  # Record the unit ordinal used by this placement.
    for key, units in units_by_key.items():  # Find references represented by distinct unit ordinals.
        if len(units) > 1:  # Multiple different units belong to one physical component.
            mergeable_keys.add(key)  # Mark this reference/library pair for merging.
    merged_by_key: Dict[Tuple[str, str], Dict[str, object]] = {}  # Store the combined record for each multi-unit component.
    result: List[Dict[str, object]] = []  # Preserve original first-occurrence ordering in the emitted deck.
    for record in components:  # Walk records in schematic order.
        key = (str(record["reference"]).upper(), str(record["lib_id"]))  # Rebuild the physical-reference key.
        if key not in mergeable_keys:  # Leave single-unit and same-unit duplicate references independent.
            result.append(record)  # Preserve the original record unchanged.
            continue  # Move to the next placement.
        merged = merged_by_key.get(key)  # Look up the combined record created by the first unit.
        if merged is None:  # Seed the combined record from the first unit encountered.
            merged = dict(record)  # Copy the top-level record without mutating the parsed placement.
            merged["pin_numbers"] = list(record["pin_numbers"])  # Copy mutable pin-number ordering.
            merged["symbol_pins"] = dict(record["symbol_pins"])  # Copy resolved pin geometry.
            merged["pin_nets"] = dict(record["pin_nets"])  # Copy resolved electrical nets.
            merged["pin_wired"] = dict(record.get("pin_wired", {}))  # Copy physical-wire attachment state.
            merged["properties"] = dict(record["properties"])  # Copy instance simulation properties.
            merged["symbol_props"] = dict(record["symbol_props"])  # Copy library simulation properties.
            merged_by_key[key] = merged  # Register the combined record.
            result.append(merged)  # Emit the combined part at its first unit's position in file order.
            continue  # Move to the next placement.
        for pin_number in record["pin_numbers"]:  # Preserve all package pin identifiers in deterministic order.
            if pin_number not in merged["pin_numbers"]:  # Avoid duplicate package pin entries.
                merged["pin_numbers"].append(pin_number)  # Append a newly encountered pin number.
        merged["symbol_pins"].update(record["symbol_pins"])  # Merge the unit's pin definitions.
        merged["pin_nets"].update(record["pin_nets"])  # Merge the unit's resolved electrical connections.
        merged["pin_wired"].update(record.get("pin_wired", {}))  # Merge its physical-wire state.
        merged["symbol_props"].update({key_name: value for key_name, value in record["symbol_props"].items() if value != ""})  # Preserve nonempty library metadata.
        merged["properties"].update({key_name: value for key_name, value in record["properties"].items() if value != ""})  # Preserve nonempty unit overrides.
        merged["line"] = min(int(merged["line"]), int(record["line"]))  # Report failures against the earliest unit placement.
    return result  # Return one emission record per physical component.


def _record_property(record: Dict[str, object], key: str) -> str:  # Resolve an instance property with a library-level fallback.
    return str(record["properties"].get(key) or record["symbol_props"].get(key) or "").strip()  # Prefer the instance override and normalize text.


def _simulation_parameters(record: Dict[str, object]) -> Dict[str, str]:  # Merge library and instance Sim.Params assignments.
    parameters = _parse_parameter_assignments(str(record["symbol_props"].get("Sim.Params") or ""))  # Start with library defaults.
    parameters.update(_parse_parameter_assignments(str(record["properties"].get("Sim.Params") or "")))  # Apply instance overrides.
    return parameters  # Return the effective parameter mapping.


def _effective_primitive(record: Dict[str, object], fallback_prefix: str) -> str:  # Resolve the actual SPICE primitive encoded by KiCad metadata.
    primitive = _record_property(record, "Spice_Primitive")  # Read legacy SPICE_Basic primitive metadata.
    if primitive != "":  # Use the leading device class from values such as V or X999.
        candidate = primitive[0].upper()  # Normalize the primitive prefix.
        if candidate in _VALID_DEVICE_PREFIXES:  # Accept only supported LTspice device classes.
            return candidate  # Return the legacy primitive class.
    parameter_type = _simulation_parameters(record).get("type", "").strip()  # Read generic SPICE type metadata.
    if parameter_type != "":  # Use type=R/type=C and similar primitive declarations.
        candidate = parameter_type[0].upper()  # Normalize the declared primitive prefix.
        if candidate in _VALID_DEVICE_PREFIXES:  # Accept only supported classes.
            return candidate  # Return the parameter-declared primitive.
    return fallback_prefix  # Fall back to the reference or Sim.Device-derived class.


def _model_name(record: Dict[str, object], value: str) -> str:  # Resolve a component model name from KiCad simulation metadata.
    sim_name = _record_property(record, "Sim.Name")  # Prefer the explicit simulation model name.
    if sim_name != "":  # Keep an authored simulation name.
        return sim_name  # Return the explicit model.
    model_parameter = _simulation_parameters(record).get("model", "").strip()  # Read generic model= metadata.
    if model_parameter != "":  # Keep the generic model assignment when present.
        return model_parameter  # Return the parameter model.
    spice_model = _record_property(record, "Spice_Model")  # Fall back to legacy SPICE_Basic model metadata.
    if spice_model != "":  # Keep the legacy model when present.
        return spice_model  # Return the legacy model text.
    return value  # Use the displayed value as the final fallback.


def _expand_kicad_library_path(library: str, kicad_path: str) -> str:  # Resolve KiCad symbol-directory variables through convert_settings.
    symbols_path = os.path.join(kicad_path, "symbols") if os.path.isdir(os.path.join(kicad_path, "symbols")) else kicad_path  # Derive the configured symbol root.
    return re.sub(r"\$\{KICAD\d*_SYMBOL_DIR\}", lambda _match: symbols_path, library, flags=re.IGNORECASE)  # Expand versioned KiCad symbol variables without hard-coded paths.


def _prepare_model_source_lines(components: List[Dict[str, object]], kicad_path: str) -> List[str]:  # Build unique includes and fallback model declarations.
    lines: List[str] = []  # Collect source lines in first-use order.
    seen: Set[str] = set()  # Deduplicate identical include and model statements.
    for record in components:  # Walk every emitted component.
        if record["exclude"] or record["power"]:  # Skip records that emit no ordinary device statement.
            continue  # Move to the next component.
        library = _record_property(record, "Sim.Library")  # Resolve the component model library.
        if library != "":  # Preserve model sources recorded by the schematic.
            expanded_library = _expand_kicad_library_path(library, kicad_path)  # Resolve KiCad installation variables from settings.
            include_line = f'.include "{expanded_library}"'  # Quote paths so spaces remain valid.
            if include_line.lower() not in seen:  # Emit each library once case-insensitively.
                seen.add(include_line.lower())  # Mark the include as emitted.
                lines.append(include_line)  # Append the model source before device calls.
        reference_prefix = str(record["reference"])[:1].upper()  # Read the reference-derived device class.
        prefix = "X" if reference_prefix == "U" else reference_prefix  # Normalize KiCad U references to subcircuits.
        sim_device = _record_property(record, "Sim.Device").upper()  # Read the explicit device class.
        prefix = _SIM_DEVICE_PREFIXES.get(sim_device, prefix)  # Apply known semiconductor/source classes.
        if sim_device == "SUBCKT":  # Explicit subcircuits always emit an X call even if their legacy symbol has another primitive hint.
            prefix = "X"  # Use the subcircuit device class.
        elif sim_device == "SPICE":  # Resolve generic SPICE metadata before assuming a subcircuit.
            prefix = _effective_primitive(record, prefix)  # Recover R/C/L primitives from generic metadata.
        if prefix not in {"D", "J", "M", "Q", "Z"} or library != "":  # Only synthesize missing primitive semiconductor models.
            continue  # Libraries and non-semiconductors require no fallback declaration.
        sim_name = _record_property(record, "Sim.Name")  # Detect an explicitly named model supplied elsewhere by schematic text.
        if sim_name != "":  # Do not replace authored model names with defaults.
            continue  # Preserve the authored external/inline model reference.
        model_type = sim_device if sim_device in {"D", "NPN", "PNP", "NJF", "PJF", "NMOS", "PMOS", "NMF", "PMF", "NIGBT", "PIGBT"} else {"D": "D", "J": "NJF", "M": "NMOS", "Q": "NPN", "Z": "NMF"}[prefix]  # Select a valid default model type.
        fallback_name = _model_name(record, str(record["value"])) or model_type  # Keep the device's authored model token so netlist round trips preserve component structure.
        model_line = f".model {fallback_name} {model_type}"  # Declare a self-contained default under the same model name used by the device.
        if model_line.lower() not in seen:  # Avoid duplicate declarations after multi-unit merging.
            seen.add(model_line.lower())  # Mark the declaration as emitted.
            lines.append(model_line)  # Append the fallback model.
    return lines  # Return all model source statements.


def _emit_device_lines(components: List[Dict[str, object]], net_names: Dict[str, str]) -> Tuple[bool, List[str], str, int]:  # Emit LTspice device lines from parsed components.
    lines: List[str] = []  # Collect the emitted device lines in schematic order.
    reserved_instance_names = {str(record["reference"]).lstrip("#").upper() for record in components if not record["power"]}  # Reserve authored names while choosing collision-free replacements.
    emitted_instance_names: Set[str] = set()  # Track names already written to the generated deck.
    for record in components:  # Walk every parsed component in file order.
        if record["exclude"]:  # Skip components excluded from simulation.
            continue  # Move to the next component.
        reference = record["reference"]  # Read the instance reference designator.
        value = record["value"]  # Read the instance value.
        if record["power"]:  # Handle power symbols specially.
            if value.upper() in _GROUND_VALUES:  # Skip ground power symbols; their net already maps to node 0.
                continue  # Move to the next component.
            if reference == "" or value == "":  # Require a usable reference and value on power symbols.
                return False, [], "MISSING_COMPONENT_PAYLOAD: power symbol is missing its Reference or Value property", record["line"]  # Return the payload error.
            source_name = _unique_power_source_name(reference, reserved_instance_names | emitted_instance_names)  # Derive a valid collision-free voltage-source name from the power reference.
            emitted_instance_names.add(source_name.upper())  # Reserve the generated name for subsequent devices.
            if not record["pin_numbers"]:  # Require at least one pin on the power symbol.
                return False, [], "UNCONNECTED_SYMBOL_PIN: power symbol has no pins", record["line"]  # Return the pin error.
            pin_root = record["pin_nets"][record["pin_numbers"][0]]  # Resolve the power pin net.
            node_name = _node_name_for_net(pin_root, net_names)  # Convert the net into an LTspice node token.
            lines.append(f"{source_name} {node_name} 0 {value}")  # Emit the power-derived voltage source.
            continue  # Move to the next component.
        if reference == "":  # Require a reference designator on ordinary components.
            return False, [], "MISSING_COMPONENT_PAYLOAD: component is missing its Reference property", record["line"]  # Return the payload error.
        if value == "":  # Require a value or model payload on ordinary components.
            return False, [], "MISSING_COMPONENT_PAYLOAD: component is missing its Value property", record["line"]  # Return the payload error.
        prefix = reference[0].upper()  # Read the LTspice device prefix from the reference.
        if prefix == "U":  # Map KiCad U references onto LTspice subcircuit calls.
            prefix = "X"  # Use the subcircuit prefix.
        sim_device = str(record["properties"].get("Sim.Device") or record["symbol_props"].get("Sim.Device") or "").upper()  # Read the simulation device class.
        prefix = _SIM_DEVICE_PREFIXES.get(sim_device, prefix)  # Let explicit simulation metadata correct KiCad reference families such as Q-designated MOSFETs.
        if sim_device == "SUBCKT" and prefix not in {"V", "I"}:  # Explicit subcircuits always use an X instance.
            prefix = "X"  # Ignore legacy primitive hints belonging to the graphical base symbol.
        elif sim_device == "SPICE" and prefix not in {"V", "I"}:  # Generic SPICE components may encode an ordinary primitive.
            prefix = _effective_primitive(record, prefix)  # Recover ordinary R/C/L and other primitive classes.
        if prefix not in _VALID_DEVICE_PREFIXES:  # Reject references whose prefix has no LTspice device class.
            return False, [], f"MISSING_COMPONENT_PAYLOAD: reference '{reference}' has no supported LTspice device prefix", record["line"]  # Return the prefix error.
        ordered_pins = _ordered_pin_numbers(record)  # Order the pin numbers by SPICE node order.
        node_tokens: List[str] = []  # Collect the ordered node tokens.
        for pin_number in ordered_pins:  # Walk the ordered pin numbers.
            pin_root = record["pin_nets"].get(pin_number)  # Resolve each pin net.
            if pin_root is None:  # Stop when a pin has no resolved net.
                return False, [], f"UNCONNECTED_SYMBOL_PIN: pin {pin_number} of '{reference}' has no resolved net", record["line"]  # Return the pin error.
            node_tokens.append(_node_name_for_net(pin_root, net_names))  # Append the node token in order.
        if prefix in _SUBSTRATE_DEFAULT_PREFIXES and len(node_tokens) == 3:  # Emulate LTspice's substrate default.
            node_tokens.append("0")  # Append the substrate node 0 for three-pin transistors.
        payload_tokens = _payload_tokens(prefix, value, record)  # Build the value/model payload tokens.
        if prefix == "X":  # Preserve the KiCad reference while adding the subcircuit invocation prefix.
            instance_name = reference if reference[:1].upper() == "X" else f"X{reference}"  # Build names such as XU1 without doubling an existing X.
        elif reference[:1].upper() != prefix:  # Correct the leading device letter when Sim.Device overrides the reference family.
            instance_name = prefix + reference[1:]  # Preserve the reference suffix while using the required SPICE prefix.
        else:  # Keep references already using the correct device prefix.
            instance_name = reference  # Reuse the original instance name.
        instance_name = _unique_ordinary_instance_name(instance_name, prefix, reserved_instance_names, emitted_instance_names)  # Renumber duplicate schematic references deterministically.
        emitted_instance_names.add(instance_name.upper())  # Reserve the final emitted name.
        lines.append(" ".join([instance_name] + node_tokens + payload_tokens))  # Emit the completed device line.
    return True, lines, "", 0  # Return the emitted device lines.


def _payload_tokens(prefix: str, value: str, record: Dict[str, object]) -> List[str]:  # Build the value payload tokens for one device class.
    sim_device = _record_property(record, "Sim.Device").upper()  # Read the effective simulation class for generic primitive payload recovery.
    primitive_value = _model_name(record, value) if sim_device == "SPICE" and prefix != "X" else value  # Use generic model metadata as an ordinary primitive's value.
    normalized_value = _normalize_passive_value(primitive_value) if prefix in {"R", "C", "L"} else primitive_value  # Protect KiCad uppercase-M passive values from SPICE milli semantics.
    if prefix == "L":  # Inductors carry LTspice's standard series resistance default.
        tokens = normalized_value.split()  # Split the normalized inductor value payload into tokens.
        if any(token.lower().startswith("rser=") for token in tokens):  # Keep an explicitly stored series resistance.
            return tokens  # Return the stored payload unchanged.
        return tokens + ["Rser=1m"]  # Append the LTspice inductor default when the payload omits it.
    if prefix in {"V", "I"}:  # Source values may carry structured KiCad simulation parameters.
        return _source_payload_tokens(value, record)  # Convert the source properties into LTspice source syntax.
    if prefix == "X":  # Subcircuit calls name the model from the simulation name when available.
        subcircuit_name = _model_name(record, value)  # Resolve the explicit subcircuit model name.
        sim_params = re.sub(r"\s*=\s*", "=", _record_property(record, "Sim.Params"))  # Normalize KiCad's optional spaces around parameter assignments.
        parameter_tokens = shlex.split(sim_params) if sim_params != "" else []  # Split authored subcircuit parameters while respecting quotes.
        parameter_tokens = [token for token in parameter_tokens if token.split("=", 1)[0].lower() not in {"type", "model", "lib"}]  # Drop KiCad's generic-device descriptor fields.
        return [subcircuit_name.replace(" ", "_")] + parameter_tokens  # Emit model then true instance parameter assignments.
    if prefix in {"D", "J", "M", "Q", "Z"}:  # Semiconductor models may carry instance parameters such as thermal terminals or geometry.
        sim_params = str(record["properties"].get("Sim.Params") or "").strip()  # Read instance-level simulation parameters.
        resolved_model = _model_name(record, value)  # Preserve the authored model name while fallback declarations use that same token.
        return [resolved_model] + (shlex.split(sim_params) if sim_params != "" else [])  # Append stored instance parameters after the model name.
    if prefix == "T":  # Lossless transmission lines require characteristic impedance and delay payloads.
        parameters = _simulation_parameters(record)  # Read z0/td metadata from the schematic.
        z0 = parameters.get("z0", parameters.get("zo", "")).strip()  # Accept KiCad's z0 spelling and LTspice's Zo spelling.
        td = parameters.get("td", "").strip()  # Read the propagation delay.
        if z0 != "" and td != "":  # Emit valid LTspice lossless-line parameters when both are supplied.
            return [f"Zo={z0}", f"Td={td}"]  # Preserve the complete T-device payload.
    return normalized_value.split()  # Return the plain value payload for all other devices.


def _normalize_passive_value(value: str) -> str:  # Convert KiCad uppercase-M mega literals into unambiguous SPICE spelling.
    tokens = value.split()  # Preserve multi-token expressions while normalizing standalone numeric literals.
    normalized: List[str] = []  # Collect normalized tokens.
    for token in tokens:  # Walk each value token independently.
        match = _MEGA_VALUE_PATTERN.fullmatch(token)  # Detect an exact numeric uppercase-M suffix.
        normalized.append(f"{match.group(1)}Meg" if match is not None else token)  # Replace only the ambiguous suffix.
    return " ".join(normalized)  # Reassemble the passive payload.


def _source_payload_tokens(value: str, record: Dict[str, object]) -> List[str]:  # Convert KiCad source properties into one LTspice source payload.
    symbol_parameters = _parse_parameter_assignments(str(record["symbol_props"].get("Sim.Params") or ""))  # Parse library defaults first.
    instance_parameters = _parse_parameter_assignments(str(record["properties"].get("Sim.Params") or ""))  # Parse instance overrides.
    parameters = dict(symbol_parameters)  # Start with the library source defaults.
    parameters.update(instance_parameters)  # Let the schematic instance override every supplied parameter.
    model = parameters.get("model", "").strip()  # Read generic SPICE source payloads stored in model=.
    if model != "":  # Generic Simulation_SPICE sources store the entire LTspice phrase in model=.
        return model.split()  # Preserve that phrase exactly as source payload tokens.
    sim_type = str(record["properties"].get("Sim.Type") or record["symbol_props"].get("Sim.Type") or "").strip().upper()  # Resolve the source waveform type.
    value_type = value.strip().upper()  # Normalize symbolic source values such as VSIN and VPULSE.
    if sim_type == "":  # Infer the waveform type from a symbolic Value when Sim.Type is absent.
        sim_type = {"VSIN": "SIN", "SINE": "SIN", "VPULSE": "PULSE", "VEXP": "EXP", "VSFFM": "SFFM"}.get(value_type, "")  # Map known source symbols.
    waveform_orders = {  # Define KiCad parameter order for LTspice waveform functions.
        "SIN": ("dc", "ampl", "f", "td", "theta", "phase", "ncycles"),  # SINE offset, amplitude, frequency, and optional timing terms.
        "SINE": ("dc", "ampl", "f", "td", "theta", "phase", "ncycles"),  # Accept the long waveform spelling too.
        "PULSE": ("y1", "y2", "td", "tr", "tf", "tw", "per", "ncycles"),  # Pulse levels, timing, period, and optional cycle count.
        "EXP": ("y1", "y2", "td1", "tau1", "td2", "tau2"),  # Exponential source parameters.
        "SFFM": ("dc", "ampl", "fc", "mdi", "fs"),  # Single-frequency FM source parameters.
    }  # Finish the waveform parameter table.
    parameter_order = waveform_orders.get(sim_type)  # Look up the selected waveform's positional parameters.
    payload: List[str] = []  # Collect waveform and optional AC payload tokens.
    if parameter_order is not None:  # Render a recognized waveform source.
        last_present = max((index for index, key in enumerate(parameter_order) if key in parameters), default=-1)  # Find the final supplied optional parameter.
        if last_present >= 0:  # Only build a function when at least one waveform parameter exists.
            waveform_values = [parameters.get(key, "0") for key in parameter_order[: last_present + 1]]  # Fill omitted intermediate parameters with SPICE zero defaults.
            function_name = "SINE" if sim_type in {"SIN", "SINE"} else sim_type  # Use LTspice's canonical sinusoidal keyword.
            payload.append(f"{function_name}({' '.join(waveform_values)})")  # Emit the ordered waveform function.
    if not payload:  # Fall back to the displayed value for DC and already-authored source phrases.
        dc_value = parameters.get("dc", "")  # Read an explicitly stored DC value when available.
        payload.extend((dc_value if dc_value != "" else value).split())  # Preserve the ordinary source payload.
    ac_value = parameters.get("ac", "").strip()  # Read the optional small-signal AC magnitude.
    if ac_value != "":  # Preserve AC data alongside a transient waveform or DC value.
        payload.extend(["AC", ac_value])  # Append LTspice's independent-source AC clause.
    return payload  # Return the completed source payload.


def _parse_parameter_assignments(parameter_text: str) -> Dict[str, str]:  # Parse whitespace-separated key=value assignments with quoted values.
    normalized = re.sub(r"\s*=\s*", "=", parameter_text.strip())  # Normalize optional whitespace around assignment operators.
    if normalized == "":  # Return early for sources without parameter metadata.
        return {}  # Report no assignments.
    try:  # Use shell-like quoting so model="dc 0 ..." remains one assignment.
        tokens = shlex.split(normalized, posix=True)  # Split the normalized property string.
    except ValueError:  # Fall back gracefully for malformed legacy quoting.
        tokens = normalized.split()  # Preserve simple assignments even when quoting is incomplete.
    assignments: Dict[str, str] = {}  # Collect normalized assignment names and values.
    for token in tokens:  # Walk each parsed property token.
        if "=" not in token:  # Ignore free-form tokens that are not assignments.
            continue  # Move to the next token.
        key, assigned_value = token.split("=", 1)  # Separate the parameter name and value.
        if key != "":  # Keep only assignments with a parameter name.
            assignments[key.lower()] = assigned_value  # Store names case-insensitively.
    return assignments  # Return the parsed assignment mapping.


def _unique_power_source_name(reference: str, used_names: Set[str]) -> str:  # Build a valid unique voltage-source name from a KiCad power reference.
    reference_body = reference.lstrip("#").strip()  # Remove KiCad's hidden-reference marker.
    sanitized_body = re.sub(r"[^A-Za-z0-9_]+", "_", reference_body) or "PWR"  # Normalize the remaining reference for SPICE.
    candidate = sanitized_body if sanitized_body.upper().startswith("V") else f"V_{sanitized_body}"  # Ensure the device name has the voltage-source prefix.
    unique_candidate = candidate  # Start with the readable reference-derived name.
    suffix = 2  # Use numeric suffixes only when the readable name collides.
    while unique_candidate.upper() in used_names:  # Search until the name is unused case-insensitively.
        unique_candidate = f"{candidate}_{suffix}"  # Add a deterministic collision suffix.
        suffix += 1  # Advance for another collision.
    return unique_candidate  # Return the valid unique source name.


def _unique_ordinary_instance_name(candidate: str, prefix: str, reserved_names: Set[str], emitted_names: Set[str]) -> str:  # Renumber duplicate ordinary references without colliding with authored names.
    if candidate.upper() not in emitted_names:  # Preserve the first occurrence of an authored reference.
        return candidate  # Return the original instance name.
    match = re.fullmatch(r"([^0-9]*)(\d+)", candidate)  # Split a conventional reference into stem and numeric suffix.
    stem = match.group(1) if match is not None else candidate + "_"  # Preserve conventional prefixes or add a separator for unusual names.
    ordinal = int(match.group(2)) + 1 if match is not None else 2  # Continue numbering after the authored suffix.
    while True:  # Search deterministically for an unused valid name.
        replacement = f"{stem}{ordinal}"  # Build the next candidate reference.
        replacement_upper = replacement.upper()  # Normalize for case-insensitive SPICE uniqueness.
        if replacement_upper not in emitted_names and replacement_upper not in reserved_names:  # Avoid both prior output and later authored references.
            return replacement  # Return the collision-free replacement.
        ordinal += 1  # Try the next integer suffix.


def _ordered_pin_numbers(record: Dict[str, object]) -> List[str]:  # Order instance pin numbers by SPICE node order.
    available_pins = set(record["pin_nets"])  # Index physically resolved and explicitly synthesized model ports.
    pin_numbers = [pin for pin in record["pin_numbers"] if pin in available_pins]  # Keep pins that have an electrical node assignment.
    sim_pins_text = str(record["properties"].get("Sim.Pins") or record["symbol_props"].get("Sim.Pins") or "")  # Read the Sim.Pins role mapping.
    if sim_pins_text == "":  # Fall back to ascending pin-number order without roles.
        return sorted(pin_numbers, key=_pin_sort_key)  # Return the numerically ordered pins.
    role_map: Dict[str, str] = {}  # Map pin numbers onto their SPICE role names.
    token_order: List[str] = []  # Preserve the role declaration order.
    for token in sim_pins_text.split():  # Walk the space-separated Sim.Pins tokens.
        if "=" not in token:  # Skip tokens without a pin-role assignment.
            continue  # Move to the next token.
        pin_part, role_part = token.split("=", 1)  # Split the pin number from the role.
        pin_part = pin_part.strip()  # Normalize the pin number token.
        role_part = role_part.strip()  # Normalize the role token.
        if pin_part not in role_map:  # Keep the first role declared for each pin.
            role_map[pin_part] = role_part  # Record the pin-to-role mapping.
            token_order.append(pin_part)  # Preserve the declaration order.
    sim_device = str(record["properties"].get("Sim.Device") or record["symbol_props"].get("Sim.Device") or "").upper()  # Read the device class.
    role_order = _ROLE_ORDER.get(sim_device)  # Look up the SPICE node ordering for the device class.
    if role_order is not None:  # Reorder pins by the known role sequence.
        role_rank = {role: rank for rank, role in enumerate(role_order)}  # Index the role sequence.
        def role_key(pin_number: str) -> Tuple[int, int]:  # Build the sort key for one pin number.
            role = role_map.get(pin_number)  # Read the assigned role.
            if role is not None and role in role_rank:  # Rank known roles by their SPICE position.
                return (0, role_rank[role])  # Return the role rank key.
            if pin_number in token_order:  # Rank unknown roles by declaration position.
                return (1, token_order.index(pin_number))  # Return the declaration position key.
            return (2, _pin_sort_key(pin_number))  # Rank unmapped pins after all role pins.
        return sorted(pin_numbers, key=role_key)  # Return the role-ordered pins.
    return [pin for pin in token_order if pin in available_pins]  # Sim.Pins is authoritative, including isolated ports belonging to unplaced units.


def _pin_sort_key(pin_number: str) -> Tuple[int, str]:  # Build a numeric-first sort key for one pin number.
    if str(pin_number).isdigit():  # Numeric pin numbers sort before symbolic ones.
        return (0, int(str(pin_number)))  # Return the integer key for numeric pins.
    return (1, str(pin_number))  # Return the string key for symbolic pins.


def _node_name_for_net(net_root: str, net_names: Dict[str, str]) -> str:  # Convert a net representative into an LTspice node token.
    name = net_names.get(net_root, "")  # Read the assigned net name.
    if name.upper() in _GROUND_VALUES:  # Ground-named nets always map to node 0.
        return "0"  # Return the LTspice ground node.
    sanitized = "".join("_" if char.isspace() else char for char in name)  # Replace whitespace inside node names.
    if sanitized == "":  # Fall back to the raw representative for unnamed nets.
        sanitized = net_root  # Use the raw net representative.
    if not sanitized[0].isalpha() and sanitized[0] != "_":  # Reject node names that start with a non-identifier character.
        sanitized = "N" + sanitized  # Prefix number- or sign-leading names with a valid identifier letter.
    return sanitized  # Return the sanitized node token.


def _parse_instance(node: SExp, index: int) -> Tuple[bool, Optional[Dict[str, object]], str, int]:  # Parse one schematic symbol instance node.
    line = _node_line_or(node, 1)  # Resolve the instance source line.
    lib_id_node = node.find_child("lib_id")  # Locate the library identifier section.
    lib_id = ""  # Default to an empty library identifier.
    if lib_id_node is not None:  # Read the identifier when present.
        lib_id_values = [child.value for child in lib_id_node.children if child.is_atom]  # Collect identifier atoms.
        lib_id = str(lib_id_values[0]) if lib_id_values else ""  # Extract the identifier text.
    if lib_id == "":  # Require a library identifier on every instance.
        return False, None, "KICAD_SCH_PARSE_ERROR", line  # Return the parse error for the missing identifier.
    at_node = node.find_child("at")  # Locate the position section.
    at_values = [child.value for child in at_node.children if child.is_atom] if at_node is not None else []  # Collect position atoms.
    if len(at_values) < 2:  # Require X and Y coordinates on every instance.
        return False, None, "KICAD_SCH_PARSE_ERROR", line  # Return the parse error for the missing position.
    instance_x = float(at_values[0])  # Read the X coordinate.
    instance_y = float(at_values[1])  # Read the Y coordinate.
    instance_angle = float(at_values[2]) if len(at_values) > 2 else 0.0  # Read the optional rotation angle.
    unit_node = node.find_child("unit")  # Locate the unit section.
    unit = 1  # Default to the first unit.
    if unit_node is not None:  # Read the unit when present.
        unit_values = [child.value for child in unit_node.children if child.is_atom]  # Collect unit atoms.
        unit = int(unit_values[0]) if unit_values else 1  # Extract the unit ordinal.
    body_style_node = node.find_child("body_style")  # Locate the body style section.
    body_style = 1  # Default to the standard body style.
    if body_style_node is not None:  # Read the body style when present.
        style_values = [child.value for child in body_style_node.children if child.is_atom]  # Collect style atoms.
        body_style = int(style_values[0]) if style_values else 1  # Extract the style ordinal.
    mirror = ""  # Default to no mirroring.
    mirror_node = node.find_child("mirror")  # Locate the optional mirror section.
    if mirror_node is not None:  # Read the mirror flag when present.
        mirror_values = [child.value for child in mirror_node.children if child.is_atom]  # Collect mirror atoms.
        mirror = str(mirror_values[0]) if mirror_values else ""  # Extract the mirror axis.
    exclude = False  # Default to simulation inclusion.
    exclude_node = node.find_child("exclude_from_sim")  # Locate the simulation exclusion flag.
    if exclude_node is not None:  # Read the flag when present.
        exclude_values = [child.value for child in exclude_node.children if child.is_atom]  # Collect flag atoms.
        exclude = str(exclude_values[0]).lower() == "yes" if exclude_values else False  # Parse the flag value.
    properties = _collect_properties(node)  # Collect the instance property overrides.
    pin_numbers: List[str] = []  # Collect the instance pin numbers in file order.
    for pin_node in node.find_children("pin"):  # Walk the instance pin sections.
        pin_values = [child.value for child in pin_node.children if child.is_atom]  # Collect pin number atoms.
        if pin_values:  # Keep pins that carry a number.
            pin_numbers.append(str(pin_values[0]))  # Store the pin number as text.
    record: Dict[str, object] = {  # Assemble the parsed instance record.
        "index": index,  # Store the schematic file order index.
        "line": line,  # Store the source line for error reporting.
        "lib_id": lib_id,  # Store the library identifier.
        "x": instance_x,  # Store the placement X coordinate.
        "y": instance_y,  # Store the placement Y coordinate.
        "angle": instance_angle,  # Store the placement rotation angle.
        "mirror": mirror,  # Store the optional mirror axis.
        "unit": unit,  # Store the symbol unit ordinal.
        "body_style": body_style,  # Store the symbol body style ordinal.
        "exclude": exclude,  # Store the simulation exclusion flag.
        "properties": properties,  # Store the instance property overrides.
        "reference": properties.get("Reference", ""),  # Store the reference designator.
        "value": properties.get("Value", ""),  # Store the value payload.
        "pin_numbers": pin_numbers,  # Store the pin number list.
        "power": False,  # Initialize the power-symbol marker.
        "symbol_props": {},  # Initialize the library property map.
        "symbol_pins": {},  # Initialize the library pin geometry map.
        "pin_nets": {},  # Initialize the pin-to-net mapping.
    }  # Finish the record assembly.
    return True, record, "", 0  # Return the parsed instance record.


def _collect_properties(node: SExp) -> Dict[str, str]:  # Collect key-value properties from one node.
    properties: Dict[str, str] = {}  # Collect the property mapping.
    for property_node in node.find_children("property"):  # Walk the property sections.
        property_values = [child.value for child in property_node.children if child.is_atom]  # Collect property atoms.
        if len(property_values) >= 2:  # Require a key and a value.
            properties[str(property_values[0])] = str(property_values[1])  # Store the property pair.
    return properties  # Return the collected property mapping.


def _symbol_excluded_from_sim(symbol_node: SExp) -> bool:  # Read the library-level simulation exclusion flag.
    exclude_node = symbol_node.find_child("exclude_from_sim")  # Locate the exclusion section.
    if exclude_node is None:  # Treat a missing flag as simulation inclusion.
        return False  # Return False when no flag exists.
    exclude_values = [child.value for child in exclude_node.children if child.is_atom]  # Collect flag atoms.
    if not exclude_values:  # Treat an empty flag as simulation inclusion.
        return False  # Return False when the flag is empty.
    return str(exclude_values[0]).lower() == "yes"  # Return the parsed flag value.


def _build_embedded_symbol_index(root: SExp) -> Dict[str, SExp]:  # Index the schematic's embedded lib_symbols definitions.
    index: Dict[str, SExp] = {}  # Collect symbols keyed by their full library identifier.
    lib_symbols_node = root.find_child("lib_symbols")  # Locate the embedded library section.
    if lib_symbols_node is None:  # Return early when the schematic caches no symbols.
        return index  # Return the empty index.
    for symbol_node in lib_symbols_node.find_children("symbol"):  # Walk every cached symbol.
        symbol_values = [child.value for child in symbol_node.children if child.is_atom]  # Collect the symbol name atoms.
        if symbol_values:  # Index symbols that carry a name.
            index[str(symbol_values[0])] = symbol_node  # Store the symbol under its full identifier.
    return index  # Return the completed embedded index.


def _split_lib_id(lib_id: str) -> Tuple[str, str]:  # Split a library identifier into nickname and symbol name.
    if ":" in lib_id:  # Split identifiers that carry a nickname.
        nickname, name = lib_id.split(":", 1)  # Split at the first colon.
        return nickname, name  # Return the nickname and symbol name.
    return "", lib_id  # Return an empty nickname for plain symbol names.


def _find_symbol_in_root(library_root: Optional[SExp], symbol_name: str) -> Optional[SExp]:  # Find one symbol inside a library root.
    if library_root is None:  # Return early for missing libraries.
        return None  # Return None when the library root is absent.
    for symbol_node in library_root.find_children("symbol"):  # Walk the top-level symbol definitions.
        symbol_values = [child.value for child in symbol_node.children if child.is_atom]  # Collect the name atoms.
        if symbol_values and str(symbol_values[0]) == symbol_name:  # Match the requested symbol name.
            return symbol_node  # Return the matching symbol node.
    return None  # Return None when the symbol is not defined in this library.


def _extract_symbol_pins(symbol_node: SExp, unit: int, body_style: int, symbol_name: str) -> Tuple[bool, Dict[str, Tuple[float, float, str]]]:  # Extract pin geometry from a symbol definition.
    unit_prefix = f"{symbol_name}_{unit}_"  # Build the sub-symbol name prefix for this unit.
    preferred_name = f"{symbol_name}_{unit}_{body_style}"  # Build the preferred sub-symbol name.
    fallback_name = f"{symbol_name}_{unit}_1"  # Build the standard body style fallback name.
    sub_symbols = symbol_node.find_children("symbol")  # Collect the nested unit sub-symbols.
    candidates: List[SExp] = []  # Collect candidate sub-symbols in preference order.
    seen: Set[int] = set()  # Track already queued sub-symbols by identity.

    def _queue_candidate(sub_symbol: SExp) -> None:  # Queue one candidate unless it is already queued.
        if id(sub_symbol) in seen:  # Skip already queued sub-symbols.
            return  # Keep the queue deduplicated.
        seen.add(id(sub_symbol))  # Mark the sub-symbol as queued.
        candidates.append(sub_symbol)  # Append the candidate to the queue.

    def _sub_symbol_name(sub_symbol: SExp) -> Optional[str]:  # Read one sub-symbol name atom.
        name_value = _first_atom_value(sub_symbol)  # Read the name atom value.
        return str(name_value) if name_value is not None else None  # Return the name text.

    for sub_symbol in sub_symbols:  # First pass: match the exact preferred and fallback names.
        name_value = _sub_symbol_name(sub_symbol)  # Read the sub-symbol name.
        if name_value in (preferred_name, fallback_name):  # Detect the preferred or fallback sub-symbol.
            _queue_candidate(sub_symbol)  # Queue the exact-name candidate.
    for sub_symbol in sub_symbols:  # Second pass: accept any sub-symbol of the requested unit.
        name_value = _sub_symbol_name(sub_symbol)  # Read the sub-symbol name.
        if name_value is not None and name_value.startswith(unit_prefix):  # Match the unit prefix.
            _queue_candidate(sub_symbol)  # Queue the unit-matching candidate.
    for sub_symbol in sub_symbols:  # Third pass: accept a unit-0 sub-symbol shared by every unit.
        name_value = _sub_symbol_name(sub_symbol)  # Read the sub-symbol name.
        if name_value is not None and name_value.startswith(f"{symbol_name}_0_"):  # Match the shared unit-0 prefix.
            _queue_candidate(sub_symbol)  # Queue the unit-0 candidate.
    for sub_symbol in sub_symbols:  # Fourth pass: accept a sub-symbol matching the unit/body-style suffix.
        name_value = _sub_symbol_name(sub_symbol)  # Read the sub-symbol name.
        if name_value is not None and name_value.endswith(f"_{unit}_{body_style}"):  # Match the unit/body-style suffix.
            _queue_candidate(sub_symbol)  # Queue the suffix-matching candidate.
    for sub_symbol in sub_symbols:  # Fifth pass: accept a unit-0 sub-symbol by suffix.
        name_value = _sub_symbol_name(sub_symbol)  # Read the sub-symbol name.
        if name_value is not None and name_value.endswith("_0_1"):  # Match the shared unit-0 body-style suffix.
            _queue_candidate(sub_symbol)  # Queue the unit-0 suffix candidate.
    for candidate in candidates:  # Walk the queued candidates in preference order.
        pins = _collect_pin_geometry(candidate)  # Extract the pins from the candidate sub-symbol.
        if not pins:  # Skip candidates that carry no pin geometry.
            continue  # Move to the next candidate.
        if unit != 0:  # Merge the unit-0 common pins shared by every unit.
            for shared_sub_symbol in sub_symbols:  # Walk the sub-symbols for shared pins.
                shared_name = _sub_symbol_name(shared_sub_symbol)  # Read the shared sub-symbol name.
                if shared_name is None:  # Skip sub-symbols without names.
                    continue  # Move to the next sub-symbol.
                if shared_name.startswith(f"{symbol_name}_0_") or shared_name.endswith("_0_1"):  # Match the unit-0 shared sub-symbol.
                    shared_pins = _collect_pin_geometry(shared_sub_symbol)  # Extract the shared pins.
                    for shared_number, shared_pin in shared_pins.items():  # Walk the shared pins.
                        pins.setdefault(shared_number, shared_pin)  # Add any shared pin not already defined by the unit.
        return True, pins  # Return the extracted pin geometry mapping.
    return False, {}  # Signal the missing pin graphics.

def _collect_pin_geometry(sub_symbol: SExp) -> Dict[str, Tuple[float, float, str]]:  # Collect pin geometry from one sub-symbol.
    pins: Dict[str, Tuple[float, float, str]] = {}  # Collect pins keyed by their number.
    for pin_node in sub_symbol.find_children("pin"):  # Walk the pin definitions.
        at_node = pin_node.find_child("at")  # Locate the pin position section.
        number_node = pin_node.find_child("number")  # Locate the pin number section.
        if at_node is None or number_node is None:  # Skip pins without position or number data.
            continue  # Move to the next pin.
        at_values = [child.value for child in at_node.children if child.is_atom]  # Collect position atoms.
        number_values = [child.value for child in number_node.children if child.is_atom]  # Collect number atoms.
        if len(at_values) < 2 or not number_values:  # Skip pins with incomplete data.
            continue  # Move to the next pin.
        pin_number = str(number_values[0])  # Read the pin number text.
        pin_name = ""  # Default to an unnamed pin.
        name_node = pin_node.find_child("name")  # Locate the optional pin name section.
        if name_node is not None:  # Read the name when present.
            name_values = [child.value for child in name_node.children if child.is_atom]  # Collect name atoms.
            pin_name = str(name_values[0]) if name_values else ""  # Extract the pin name text.
        pins[pin_number] = (float(at_values[0]), float(at_values[1]), pin_name)  # Store the pin geometry.
    return pins  # Return the collected pin geometry mapping.


def _symbol_has_any_pins(symbol_node: Optional[SExp]) -> bool:  # Detect whether a symbol defines any pin geometry anywhere.
    if symbol_node is None:  # Treat missing symbols as pinless.
        return False  # Return False for missing definitions.
    for sub_symbol in symbol_node.find_children("symbol"):  # Walk every unit sub-symbol.
        if _collect_pin_geometry(sub_symbol):  # Detect any sub-symbol that carries pins.
            return True  # Report that the symbol has usable pins.
    return False  # Report that the symbol is purely graphical.


def _transform_point(local_x: float, local_y: float, origin_x: float, origin_y: float, angle: float, mirror: str) -> Tuple[float, float]:  # Transform a symbol-local point into schematic coordinates.
    if mirror == "x":  # Mirror across the horizontal X axis.
        local_y = -local_y  # Negate the local Y coordinate.
    elif mirror == "y":  # Mirror across the vertical Y axis.
        local_x = -local_x  # Negate the local X coordinate.
    radians = math.radians(angle)  # Convert the placement angle to radians.
    cosine = math.cos(radians)  # Compute the rotation cosine.
    sine = math.sin(radians)  # Compute the rotation sine.
    rotated_x = local_x * cosine - local_y * sine  # Rotate in KiCad symbol space before changing coordinate handedness.
    rotated_y = local_x * sine + local_y * cosine  # Compute the rotated symbol-space Y offset.
    return origin_x + rotated_x, origin_y - rotated_y  # Flip the Y axis after rotation and return the schematic-space point.


def _collect_wire_segments(root: SExp, union_find: _UnionFind) -> List[Tuple[float, float, float, float, str, str]]:  # Collect wire polylines as merged point segments.
    segments: List[Tuple[float, float, float, float, str, str]] = []  # Collect the segment records.
    for wire_node in root.find_children("wire"):  # Walk the wire sections.
        points_node = wire_node.find_child("pts")  # Locate the polyline point list.
        if points_node is None:  # Skip wires without a point list.
            continue  # Move to the next wire.
        coordinates: List[Tuple[float, float]] = []  # Collect the polyline coordinates.
        for xy_node in points_node.find_children("xy"):  # Walk the coordinate pairs.
            xy_values = [child.value for child in xy_node.children if child.is_atom]  # Collect coordinate atoms.
            if len(xy_values) >= 2:  # Keep complete coordinate pairs.
                coordinates.append((float(xy_values[0]), float(xy_values[1])))  # Store the coordinate pair.
        if len(coordinates) < 2:  # Skip degenerate wires with fewer than two points.
            continue  # Move to the next wire.
        for position in range(len(coordinates) - 1):  # Split the polyline into consecutive segments.
            start_x, start_y = coordinates[position]  # Read the segment start point.
            end_x, end_y = coordinates[position + 1]  # Read the segment end point.
            start_key = _point_key(start_x, start_y)  # Register the start point key.
            end_key = _point_key(end_x, end_y)  # Register the end point key.
            union_find.add(start_key)  # Ensure the start point exists.
            union_find.add(end_key)  # Ensure the end point exists.
            union_find.union(start_key, end_key)  # Join the endpoints through the segment.
            segments.append((start_x, start_y, end_x, end_y, start_key, end_key))  # Store the segment record.
    return segments  # Return the collected wire segments.


